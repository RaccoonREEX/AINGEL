import { useEffect, useState } from "react";
import { APIError, api } from "../api";
import Field from "./Field";
import PrivateMediaConsent, { imageTestFields } from "./PrivateMediaConsent";
import { localVoice } from "./aingel/browserSpeech";
import { speechParts } from "./aingel/vision";
import {
  askBody, clampPage, DOCUMENT_FIXTURES, endsDocument, openForm,
  type DocumentAction, type DocumentAnswer, type DocumentInfo, type DocumentPage,
} from "./aingel/documents";
import type { WithProfile } from "../ui";

/**
 * «Leer un documento»: a PDF (or a photo of a page) read page by page. The page text comes from the PDF itself;
 * scanned pages are transcribed by Meta only when asked; explanations are marked as generated by AI.
 */
export default function DocumentReader({ profile, t, locale, busy, run }: Pick<WithProfile, "profile" | "t" | "locale" | "busy" | "run">) {
  const es = locale === "es-EC";
  const L = (spanish: string, english: string) => (es ? spanish : english);
  const [file, setFile] = useState<File | null>(null),
    [fixture, setFixture] = useState("book_pdf"),
    [privateTest, setPrivateTest] = useState(false);
  const [doc, setDoc] = useState<DocumentInfo | null>(null),
    [page, setPage] = useState<DocumentPage | null>(null),
    [goTo, setGoTo] = useState("1"),
    [query, setQuery] = useState(""),
    [results, setResults] = useState<{ page: number; excerpt: string }[] | null>(null),
    [answer, setAnswer] = useState<{ label: string; result: DocumentAnswer } | null>(null),
    [question, setQuestion] = useState(""),
    [scope, setScope] = useState<"page" | "document">("page"),
    [message, setMessage] = useState("");
  const base = doc ? `documents/${doc.document}/` : "";
  useEffect(() => () => window.speechSynthesis?.cancel(), []);

  const failed = (error: unknown) => {
    const code = error instanceof APIError ? String((error.detail as { error?: unknown } | null)?.error ?? "") : "";
    if (endsDocument(code)) { setDoc(null); setPage(null); setAnswer(null); }
    throw error;
  };
  const load = async (number: number, info: DocumentInfo) => {
    const next = await api<DocumentPage>(`documents/${info.document}/pages/${clampPage(number, info.pages)}/`).catch(failed);
    setPage(next); setGoTo(String(next.page)); setAnswer(null); setMessage("");
  };
  const show = (number: number) => run(async () => { if (doc) await load(number, doc); });
  const speak = (text: string) => {
    const synth = window.speechSynthesis;
    // Local voices only: a network voice would send the document to its provider.
    const voice = synth ? localVoice(profile.locale) : null;
    if (!synth || !voice) { setMessage(t("noVoice")); return; }
    synth.cancel();
    for (const part of speechParts(text)) {
      const utterance = new SpeechSynthesisUtterance(part);
      utterance.lang = profile.locale;
      utterance.voice = voice;
      synth.speak(utterance);
    }
  };
  const close = () => {
    window.speechSynthesis?.cancel();
    // The server deletes its copy now instead of at expiry.
    if (doc) void api(`documents/${doc.document}/`, "DELETE").catch(() => undefined);
    setDoc(null); setPage(null); setAnswer(null); setResults(null);
  };
  const ask = (action: DocumentAction, label: string, askScope: "page" | "document" = "page") => run(async () => {
    if (!doc || !page) return;
    setAnswer(null);
    const result = await api<DocumentAnswer>(`${base}ask/`, "POST", askBody(action, page.page, askScope, question)).catch(failed);
    setAnswer({ label, result });
  });

  if (!doc) {
    return (
      <section className="panel" aria-labelledby="document-heading">
        <h2 id="document-heading">{L("Leer un documento", "Read a document")}</h2>
        <p className="hint">{L(
          "AINGEL lee el texto del propio PDF página por página, sin inventar nada. Las páginas escaneadas se transcriben con IA solo si lo pides. El servidor guarda el documento cifrado hasta 2 horas, o hasta que lo cierres.",
          "AINGEL reads the PDF's own text page by page, inventing nothing. Scanned pages are transcribed by AI only if you ask. The server keeps the document encrypted for up to 2 hours, or until you close it.",
        )}</p>
        <form
          onSubmit={(e) => {
            e.preventDefault();
            const form = file
              ? openForm(profile.locale, { file, name: file.name, profile: profile.id, testFields: imageTestFields(profile, privateTest) })
              : openForm(profile.locale, { fixture });
            setPrivateTest(false);
            void run(async () => {
              const info = await api<DocumentInfo>("documents/", "POST", form);
              setDoc(info); setResults(null);
              await load(1, info);
            });
          }}
        >
          <div className="actions">
            <Field label={L("PDF o foto de una página", "PDF or photo of a page")}>
              <input type="file" accept="application/pdf,image/jpeg,image/png,image/webp" onChange={(e) => setFile(e.target.files?.[0] || null)} />
            </Field>
            {!file && (
              <Field label={L("O un documento sintético del servidor", "Or a server synthetic document")}>
                <select value={fixture} onChange={(e) => setFixture(e.target.value)}>
                  {Object.entries(DOCUMENT_FIXTURES).map(([id, names]) => <option key={id} value={id}>{names[es ? 0 : 1]}</option>)}
                </select>
              </Field>
            )}
          </div>
          {file && <PrivateMediaConsent profile={profile} kind="image" checked={privateTest} onChange={setPrivateTest} disabled={busy} />}
          <button className="primary" disabled={busy}>{L("Abrir documento", "Open document")}</button>
        </form>
      </section>
    );
  }

  return (
    <section className="panel" aria-labelledby="document-heading">
      <h2 id="document-heading">{doc.title || L("Documento", "Document")}</h2>
      <p className="hint">{L(`${doc.pages} páginas`, `${doc.pages} pages`)}{doc.synthetic_fixture && ` · ${L("documento sintético", "synthetic document")}`}</p>
      {doc.outline.length > 0 && (
        <nav aria-label={L("Capítulos", "Chapters")}>
          <ul className="document-outline">
            {doc.outline.map((row) => (
              <li key={`${row.page}-${row.title}`} style={{ marginInlineStart: `${row.level}em` }}>
                <button type="button" className="link" disabled={busy} onClick={() => void show(row.page)}>{row.title} · {L("pág.", "p.")} {row.page}</button>
              </li>
            ))}
          </ul>
        </nav>
      )}
      <div className="actions">
        <button type="button" disabled={busy || !page || page.page <= 1} onClick={() => page && void show(page.page - 1)}>{L("Página anterior", "Previous page")}</button>
        <button type="button" disabled={busy || !page || page.page >= doc.pages} onClick={() => page && void show(page.page + 1)}>{L("Página siguiente", "Next page")}</button>
        <form className="actions" onSubmit={(e) => { e.preventDefault(); void show(Number(goTo)); }}>
          <Field label={L("Ir a la página", "Go to page")}>
            <input type="number" min={1} max={doc.pages} value={goTo} onChange={(e) => setGoTo(e.target.value)} />
          </Field>
          <button disabled={busy}>{L("Ir", "Go")}</button>
        </form>
      </div>
      {page && (
        <article aria-live="polite" aria-label={L(`Página ${page.page} de ${page.pages}`, `Page ${page.page} of ${page.pages}`)}>
          <h3>{L(`Página ${page.page} de ${page.pages}`, `Page ${page.page} of ${page.pages}`)}{page.chapter && ` · ${page.chapter}`}</h3>
          {page.transcribed && <p className="badge">{L("Transcripción hecha con IA: puede tener errores", "AI transcription: it may contain errors")}</p>}
          {page.has_text
            ? page.paragraphs.map((paragraph, i) => <p key={i} className="scene-result">{paragraph}</p>)
            : <p>{L("Esta página no tiene texto: parece escaneada o ser solo una imagen.", "This page has no text: it looks scanned or is only a picture.")}</p>}
          <div className="actions">
            {page.has_text && <button type="button" onClick={() => speak(page.text)}>{t("speak")}</button>}
            <button type="button" onClick={() => window.speechSynthesis?.cancel()}>{t("stopSpeaking")}</button>
            {!page.has_text && (
              <button type="button" className="primary" disabled={busy} onClick={() => void run(async () => {
                const result = await api<DocumentPage & DocumentAnswer>(`${base}pages/${page.page}/transcribe/`, "POST").catch(failed);
                if (result.mode === "mock") setMessage(result.text);
                else await load(page.page, doc);
              })}>{L("Transcribir esta página con IA", "Transcribe this page with AI")}</button>
            )}
          </div>
        </article>
      )}
      <h3>{L("Entender el documento (IA)", "Understand the document (AI)")}</h3>
      <div className="actions">
        <button type="button" disabled={busy || !page} onClick={() => void ask("explain", L("Explicación de la página", "Page explanation"))}>{L("Explicar esta página", "Explain this page")}</button>
        <button type="button" disabled={busy || !page} onClick={() => void ask("summarize", L("Resumen de la página", "Page summary"))}>{L("Resumir esta página", "Summarize this page")}</button>
        <button type="button" disabled={busy || !page} onClick={() => void ask("figures", L("Figuras de la página", "Page figures"))}>{L("Describir figuras y tablas", "Describe figures and tables")}</button>
        <button type="button" disabled={busy || !page} onClick={() => void ask("summarize", L("Resumen del documento", "Document summary"), "document")}>{L("Resumir todo el documento", "Summarize the whole document")}</button>
      </div>
      {!doc.synthetic_fixture && (
        <form onSubmit={(e) => { e.preventDefault(); if (question.trim()) void ask("question", question.trim(), scope); }}>
          <div className="actions">
            <Field label={L("Pregunta sobre el documento", "Question about the document")}>
              <input maxLength={600} value={question} onChange={(e) => setQuestion(e.target.value)} />
            </Field>
            <Field label={L("Buscar la respuesta en", "Look for the answer in")}>
              <select value={scope} onChange={(e) => setScope(e.target.value as "page" | "document")}>
                <option value="page">{L("Esta página", "This page")}</option>
                <option value="document">{L("Todo el documento", "The whole document")}</option>
              </select>
            </Field>
            <button disabled={busy || !question.trim()}>{L("Preguntar", "Ask")}</button>
          </div>
        </form>
      )}
      {answer && (
        <div aria-live="polite">
          <h4>{answer.label}</h4>
          <span className="badge">{t(answer.result.mode === "meta" ? "meta" : "mock")}</span>
          {answer.result.paragraphs.map((paragraph, i) => <p key={i}>{paragraph}</p>)}
          <button type="button" onClick={() => speak(answer.result.text)}>{t("speak")}</button>
        </div>
      )}
      <form onSubmit={(e) => { e.preventDefault(); void run(async () => setResults((await api<{ results: { page: number; excerpt: string }[] }>(`${base}search/?q=${encodeURIComponent(query)}`).catch(failed)).results)); }}>
        <div className="actions">
          <Field label={L("Buscar en el documento", "Search the document")}>
            <input maxLength={100} value={query} onChange={(e) => setQuery(e.target.value)} />
          </Field>
          <button disabled={busy || query.trim().length < 2}>{L("Buscar", "Search")}</button>
        </div>
      </form>
      {results && (
        <div aria-live="polite">
          {results.length === 0 ? <p>{L("No aparece en el texto del documento.", "It does not appear in the document text.")}</p> : (
            <ul>
              {results.map((hit) => (
                <li key={hit.page}><button type="button" className="link" onClick={() => void show(hit.page)}>{L("Página", "Page")} {hit.page}</button>: {hit.excerpt}</li>
              ))}
            </ul>
          )}
        </div>
      )}
      {message && <p role="status">{message}</p>}
      <button type="button" onClick={close}>{L("Cerrar documento", "Close document")}</button>
    </section>
  );
}
